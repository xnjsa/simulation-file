function outputs = func(t,y)

% Parameters (it is recommended to add semicolons to all statements)
Ra = 10; % Basic payoff of the sports actor
Rb = 10; % Basic payoff of the tourism actor
Rc = 10; % Basic payoff of the platform actor
Rd = 10; % Basic payoff of consumers
Ca = 3;  % Additional cost of the sports actor
Cb = 3;  % Additional cost of the tourism actor
Cc = 2;  % Additional cost of the platform actor
Cd = 1;   % Additional cost of consumers
U1 = 0.1; % Commission rate of the platform under the proactive empowerment strategy
U2 = 0.01; % Basic service fee rate of the platform under the conventional display strategy
R  = 10;   % Synergistic payoff of the sports and tourism actors   【Contract mechanism scenario parameter】
e  = 2;  % Profit-sharing ratio of the sports actor   【Contract mechanism scenario parameter】
r  = 5;   % Short-term benefit obtained by the defecting actor from resource sharing   【Contract mechanism scenario parameter】
g  = 10;   % Breach cost incurred by the defecting actor due to defection from cooperation   【Contract mechanism scenario parameter】
T  = 1.2;  % Platform capability for deep empowerment T >   【Synergy mechanism scenario parameter】
n  = 1.1;  % User-feedback value-added coefficient n > 1    【Synergy mechanism scenario parameter】
X  = 0;   % Special government subsidy for the sports or tourism actor  【Incentive mechanism scenario parameter】
F  = 7;   % Special government subsidy for platform digitalization  【Incentive mechanism scenario parameter】
G  = 5;   % Government subsidy for consumers    【Incentive mechanism scenario parameter】
W  = 2;   % Government compliance regulation of the sports and tourism actors   【Regulatory mechanism scenario parameter】
O  = 2;   % Government tax penalty on passive behavior by the sports and tourism actors   【Regulatory mechanism scenario parameter】
P  = 1.1;  % Experience value coefficient provided by the sports or tourism actor to consumers


outputs = zeros(4,1);

outputs(1) = y(1)*(1-y(1))*(O - Ca - W + X + g + Ca*y(2) - Ra*y(4) - Ra*y(3) + 2*W*y(2) - r*y(2) + Ra*T*y(3) + R*e*y(2) + Ra*n*y(4) + Ra*y(4)*y(2) + Ra*y(4)*y(3) + Ra*y(2)*y(3) - R*e*y(4)*y(2) - R*e*y(2)*y(3) - Ra*n*y(4)*y(2) - Ra*n*y(4)*y(3) - Ra*y(4)*y(2)*y(3) - Ra*T*y(4)*y(3) - Ra*T*y(2)*y(3) + R*T*e*y(2)*y(3) + Ra*T*n*y(4)*y(3) + Ra*T*y(4)*y(2)*y(3) + R*e*n*y(4)*y(2) + R*e*y(4)*y(2)*y(3) + Ra*n*y(4)*y(2)*y(3) - R*T*U1*e*y(2)*y(3) - R*T*e*y(4)*y(2)*y(3) - Ra*T*n*y(4)*y(2)*y(3) - R*e*n*y(4)*y(2)*y(3) + R*T*U1*e*y(4)*y(2)*y(3) + R*T*e*n*y(4)*y(2)*y(3) - R*T*U1*e*n*y(4)*y(2)*y(3));

outputs(2) = y(2)*(1-y(2))*(O - Cb - W + X + g + Cb*y(1) - Rb*y(4) + R*y(1) - Rb*y(3) + 2*W*y(1) - r*y(1) + Rb*T*y(3) - R*e*y(1) + Rb*n*y(4) - R*y(4)*y(1) + Rb*y(4)*y(1) + Rb*y(4)*y(3) - R*y(1)*y(3) + Rb*y(1)*y(2) + R*e*y(4)*y(1) + R*e*y(1)*y(3) + R*n*y(4)*y(1) - Rb*n*y(4)*y(1) - Rb*n*y(4)*y(3) + R*y(4)*y(1)*y(3) - Rb*y(4)*y(1)*y(3) - Rb*T*y(4)*y(3) + R*T*y(1)*y(3) - Rb*T*y(1)*y(3) - R*T*U1*y(1)*y(3) - R*T*e*y(1)*y(3) + Rb*T*n*y(4)*y(3) - R*T*y(4)*y(1)*y(3) + Rb*T*y(4)*y(1)*y(3) - R*e*n*y(4)*y(1) - R*e*y(4)*y(1)*y(3) - R*n*y(4)*y(1)*y(3) + Rb*n*y(4)*y(1)*y(3) + R*T*U1*e*y(1)*y(3) + R*T*U1*y(4)*y(1)*y(3) + R*T*e*y(4)*y(1)*y(3) + R*T*n*y(4)*y(1)*y(3) - Rb*T*n*y(4)*y(1)*y(3) + R*e*n*y(4)*y(1)*y(3) - R*T*U1*e*y(4)*y(1)*y(3) - R*T*U1*n*y(4)*y(1)*y(3) - R*T*e*n*y(4)*y(1)*y(3) + R*T*U1*e*n*y(4)*y(1)*y(3));

outputs(3) = y(3)*(1 - y(3))*( ...
    F*y(1) - Cc + F*y(2) - Ra*U1*y(1) - Rb*U1*y(2) ...
    - F*y(4)*y(2) - F*y(1)*y(2) + F*y(4)*y(1)*y(2) ...
    + Ra*T*U1*y(1) + Rb*T*U1*y(2) ...
    - Cb*U2*y(4)*y(1) + Cd*U2*y(4)*y(1) ...
    + Ra*U1*y(1)*y(2) + Rb*U1*y(1)*y(2) ...
    + R*T*U1*y(1)*y(2) - Ra*T*U1*y(1)*y(2) - Rb*T*U1*y(1)*y(2) ...
    + Cb*U2*y(4)*y(1)*y(2) - Cc*U2*y(4)*y(1)*y(2) ...
    - R*T*U1*y(4)*y(1)*y(2) + R*T*U1*n*y(4)*y(1)*y(2) );

outputs(4) = ( ...
    y(4)*(y(4) - 1) * ( ...
        Cd*P^2*T - G*P^2*T + P^2*Rd*y(3) + Rd*y(1)*y(2)*y(3) ...
        - P^3*Rd*T*y(1) - P^3*Rd*T*y(2) ...
        - P^2*Rd*y(1)*y(3) - P^2*Rd*y(2)*y(3) - P^2*Rd*T^2*y(3) ...
        + P*Rd*T*y(1) + P*Rd*T*y(2) + P*Rd*y(1)*y(3) + P*Rd*y(2)*y(3) ...
        + Rd*T*y(1)*y(2) ...
        + P^2*Rd*T^2*y(1)*y(3) - P^3*Rd*T^2*y(1)*y(3) ...
        + P^2*Rd*T^2*y(2)*y(3) - P^3*Rd*T^2*y(2)*y(3) ...
        - 2*P*Rd*T*y(1)*y(2) - P*Rd*T*y(1)*y(3) - P*Rd*T*y(2)*y(3) ...
        - 2*P*Rd*y(1)*y(2)*y(3) - Rd*T*y(1)*y(2)*y(3) ...
        + 2*P^3*Rd*T*y(1)*y(2) - P^4*Rd*T*y(1)*y(2) ...
        + P^3*Rd*T*y(1)*y(3) + P^3*Rd*T*y(2)*y(3) ...
        + P^2*Rd*y(1)*y(2)*y(3) ...
        - 2*P^3*Rd*T*y(1)*y(2)*y(3) + P^4*Rd*T*y(1)*y(2)*y(3) ...
        - P^2*Rd*T^2*y(1)*y(2)*y(3) + 2*P^3*Rd*T^2*y(1)*y(2)*y(3) ...
        - P^4*Rd*T^2*y(1)*y(2)*y(3) + 2*P*Rd*T*y(1)*y(2)*y(3) ...
    ) ...
) / (P^2*T);

end
